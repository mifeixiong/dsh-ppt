import { PptError } from './errors.ts'
import { registeredFont } from './fonts.ts'
import { SLIDE_TYPES } from './slide-taxonomy.ts'

/**
 * A deck theme is a reusable design recipe: colours, type roles, a page rhythm
 * and the decoration vocabulary that holds them together. The plugin shipped
 * without one, so every deck was designed from nothing and the quality ceiling
 * was whatever the model improvised that turn. A theme does not replace the
 * agent's design pass — it gives the pass a vetted starting point and a
 * verifiable palette, the way a template does for a human designer.
 */

export type ArtComposition = typeof ART_COMPOSITIONS[number]
export type ArtBackground = typeof ART_BACKGROUNDS[number]
export type ArtDensity = typeof ART_DENSITIES[number]
export type ArtTitleTreatment = typeof ART_TITLE_TREATMENTS[number]
export type ArtFramePolicy = typeof ART_FRAME_POLICIES[number]

export interface ThemeFontRole {
  family: string
  weight: number
}

/**
 * Type is the loudest part of a deck that no palette can carry. The roles above
 * choose a family; this block says how the family is set: tracking, case and
 * numerals. Rules are declarative strings because the HTML is still authored by
 * the agent, not generated by a layout engine.
 */
export interface ThemeTypeTreatment {
  /** Letter-spacing for display type, e.g. "-0.02em". */
  display_tracking: string
  /** Letter-spacing for small uppercase labels; wide tracking is the premium tell. */
  label_tracking: string
  /** Letter-spacing for body copy. */
  body_tracking: string
  /** Case convention for eyebrows and labels. */
  label_case: 'sentence' | 'upper'
  /** Figure style for metrics and tables. */
  numerals: 'tabular' | 'proportional'
  /** Comfortable line length for body copy, expressed for a human, e.g. "32-40 CJK characters". */
  measure: string
}

/**
 * A linear gradient the theme permits on poster pages. Stops are opaque hex so
 * the same recipe can render in the HTML preview, in the native PPTX slide
 * background, and in a contrast audit. A gradient is never the only field: the
 * first stop is the solid fallback for older viewers and for rasterised output.
 */
export interface ThemeGradient {
  /** Name from uiGradients / Color Hunt / the design system it was adapted from. */
  name: string
  /** CSS angle in degrees: 0 = to top, 90 = to right, 180 = to bottom. */
  angle: number
  /** Two to four opaque stops, evenly spaced. */
  stops: readonly string[]
  /** Tonal group the gradient belongs to, so text contrast can be checked. */
  group: 'base' | 'inverse' | 'accent'
  /** How many pages of a deck may carry this gradient; gradients stay rare. */
  max_pages: number
  /** One line the HTML must obey: fallback, pairing and where it is allowed. */
  note: string
}

export interface PptTheme {
  id: string
  /** Display name shown to the user when the theme is offered. */
  name: string
  concept: string
  audience_effect: string
  scenes: readonly string[]
  /**
   * Where the palette values come from. Every built-in theme traces to a
   * published design system or a public palette site so a colour can be audited
   * instead of trusted; a theme authored from a brand book records that source
   * here too.
   */
  palette_source: string
  palette: {
    background: readonly string[]
    surface: readonly string[]
    accent: string
    /**
     * Accent for the inverted tonal group. A single accent cannot clear 4.5:1 on
     * both a light and a dark field, so every theme carries the pair and the plan
     * tells the model which one each page uses.
     */
    accent_inverted: string
    text: readonly string[]
  }
  typography: {
    display: ThemeFontRole
    body: ThemeFontRole
    latin: ThemeFontRole
    code: ThemeFontRole
  }
  /** How the four font roles are set, not just which families they use. */
  type_treatment: ThemeTypeTreatment
  /**
   * Bold display-type moves for poster pages. Poster pages are where a deck is
   * allowed to be typographic rather than tidy; the plan walks this list so a
   * deck does not put the same square title block on every page.
   */
  poster_moves: readonly string[]
  /** One-line signature device, repeated across the deck as its identity. */
  signature: string
  /** Composition preference, repeated across the deck in page order. */
  composition_cycle: readonly ArtComposition[]
  /** Background rhythm preference, repeated across the deck in page order. */
  background_cycle: readonly ArtBackground[]
  /** Rhythm limits the theme's own decoration was designed against. */
  rhythm_limits: {
    max_grouped_frame_slides: number
    max_same_composition_run: number
  }
  /** Decoration moves a page may use; every entry must survive the HTML whitelist. */
  decoration: readonly string[]
  /** Anti-patterns that would break this theme even inside the palette. */
  avoid: readonly string[]
  /** How photography, screenshots and generated assets are treated. */
  image_treatment: string
  /** The theme's permitted gradients. Most themes carry none or one. */
  gradients: readonly ThemeGradient[]
  /** What each composition means inside this theme. */
  layout_notes: Readonly<Partial<Record<ArtComposition, string>>>
}

const HEX = /^#[0-9A-F]{6}$/u
const GRADIENT_GROUP = ['base', 'inverse', 'accent'] as const
/** Poster compositions are the only pages allowed to carry a gradient field. */
const POSTER_COMPOSITIONS: readonly ArtComposition[] = ['hero', 'full-bleed', 'closing', 'quote']

/** WCAG 2.1 relative luminance of an #RRGGBB colour. */
export function relativeLuminance(color: string): number {
  const hex = color.replace('#', '')
  const channel = (offset: number): number => {
    const value = Number.parseInt(hex.slice(offset, offset + 2), 16) / 255
    return value <= 0.03928 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4
  }
  return 0.2126 * channel(0) + 0.7152 * channel(2) + 0.0722 * channel(4)
}

/** WCAG 2.1 contrast ratio between two #RRGGBB colours, from 1 to 21. */
export function contrastRatio(a: string, b: string): number {
  const first = relativeLuminance(a)
  const second = relativeLuminance(b)
  const lighter = Math.max(first, second)
  const darker = Math.min(first, second)
  return (lighter + 0.05) / (darker + 0.05)
}

/** The CSS form of a theme gradient, so the model never has to assemble it. */
export function gradientCss(gradient: ThemeGradient): string {
  return `linear-gradient(${gradient.angle}deg, ${gradient.stops.join(', ')})`
}

/** Text colour a gradient page must use, picked from the gradient's tonal group. */
function gradientText(theme: PptTheme, gradient: ThemeGradient): string {
  if (gradient.group === 'base') return theme.palette.text[0]!
  if (gradient.group === 'inverse') return theme.palette.text[1 % theme.palette.text.length]!
  const candidates = theme.palette.text
  let best = candidates[0]!
  let bestRatio = -1
  for (const candidate of candidates) {
    const ratio = Math.min(...gradient.stops.map(stop => contrastRatio(candidate, stop)))
    if (ratio > bestRatio) {
      best = candidate
      bestRatio = ratio
    }
  }
  return best
}

export interface ThemeFinding {
  code: string
  severity: 'warning' | 'error'
  message: string
}

/**
 * Contrast is the one part of "looks good" that can be checked by machine, so
 * every theme is held to it at load time rather than discovered in review.
 *
 * A palette is a set of tonal groups, not a cross product: `background[i]`,
 * `surface[i]` and `text[i]` belong together, so text is paired by index. The
 * accent is a single value that must stay readable on the primary group; on an
 * inverted group it is expected to be swapped for the theme's inverted accent,
 * which is reported as a warning rather than a failure. Gradients are checked
 * against the same text rule as the field they replace.
 */
export function themeFindings(theme: PptTheme): ThemeFinding[] {
  const findings: ThemeFinding[] = []
  const check = (label: string, foreground: string, background: string, minimum: number): void => {
    const ratio = contrastRatio(foreground, background)
    if (ratio < minimum) {
      findings.push({
        code: 'THEME_CONTRAST_LOW', severity: 'error',
        message: `${theme.id}: ${label} contrast ${ratio.toFixed(2)}:1 is below ${minimum}:1 (${foreground} on ${background})`,
      })
    }
  }
  const groups = Math.max(theme.palette.background.length, theme.palette.surface.length, theme.palette.text.length)
  for (let index = 0; index < groups; index += 1) {
    const background = theme.palette.background[index % theme.palette.background.length]!
    const surface = theme.palette.surface[index % theme.palette.surface.length]!
    const text = theme.palette.text[index % theme.palette.text.length]!
    check(`body text ${text} on background ${background}`, text, background, 4.5)
    check(`body text ${text} on surface ${surface}`, text, surface, 4.5)
    if (index === 0) {
      check(`accent on background ${background}`, theme.palette.accent, background, 4.5)
      check(`accent on surface ${surface}`, theme.palette.accent, surface, 4.5)
      continue
    }
    check(`inverted accent on background ${background}`, theme.palette.accent_inverted, background, 4.5)
    check(`inverted accent on surface ${surface}`, theme.palette.accent_inverted, surface, 4.5)
  }
  for (const gradient of theme.gradients) {
    const text = gradientText(theme, gradient)
    for (const stop of gradient.stops) {
      check(`gradient "${gradient.name}" text ${text} on ${stop}`, text, stop, 4.5)
    }
  }
  return findings
}

function requireColor(theme: string, label: string, value: string): void {
  if (!HEX.test(value)) {
    throw new PptError('PPT_THEME_INVALID', `theme ${theme} ${label} must be #RRGGBB: ${value}`)
  }
}

function requireFont(theme: string, role: string, family: string): void {
  if (registeredFont(family) === undefined) {
    throw new PptError('PPT_THEME_INVALID', `theme ${theme} ${role} font is not in the approved registry: ${family}`)
  }
}

function requireText(theme: string, label: string, value: string, max: number): void {
  if (value.trim().length === 0 || [...value].length > max) {
    throw new PptError('PPT_THEME_INVALID', `theme ${theme} ${label} must contain 1..${max} characters`)
  }
}

export function validateTheme(theme: PptTheme): PptTheme {
  if (!/^[a-z0-9][a-z0-9-]{1,40}$/u.test(theme.id)) {
    throw new PptError('PPT_THEME_INVALID', `theme id must be lower-kebab-case: ${theme.id}`)
  }
  if (theme.palette.background.length === 0 || theme.palette.background.length > 4) {
    throw new PptError('PPT_THEME_INVALID', `theme ${theme.id} needs 1..4 background colours`)
  }
  if (theme.palette.surface.length === 0 || theme.palette.surface.length > 4) {
    throw new PptError('PPT_THEME_INVALID', `theme ${theme.id} needs 1..4 surface colours`)
  }
  if (theme.palette.text.length === 0 || theme.palette.text.length > 4) {
    throw new PptError('PPT_THEME_INVALID', `theme ${theme.id} needs 1..4 text colours`)
  }
  theme.palette.background.forEach((value, index) => requireColor(theme.id, `background[${index}]`, value))
  theme.palette.surface.forEach((value, index) => requireColor(theme.id, `surface[${index}]`, value))
  theme.palette.text.forEach((value, index) => requireColor(theme.id, `text[${index}]`, value))
  requireColor(theme.id, 'accent', theme.palette.accent)
  requireColor(theme.id, 'accent_inverted', theme.palette.accent_inverted)
  for (const role of ['display', 'body', 'latin', 'code'] as const) {
    const entry = theme.typography[role]
    requireFont(theme.id, role, entry.family)
    if (!Number.isInteger(entry.weight) || entry.weight < 100 || entry.weight > 900 || entry.weight % 100 !== 0) {
      throw new PptError('PPT_THEME_INVALID', `theme ${theme.id} ${role} weight must be a 100..900 multiple of 100: ${entry.weight}`)
    }
  }
  requireText(theme.id, 'signature', theme.signature, 140)
  requireText(theme.id, 'image_treatment', theme.image_treatment, 240)
  if (theme.poster_moves.length < 2 || theme.poster_moves.length > 5) {
    throw new PptError('PPT_THEME_INVALID', `theme ${theme.id} needs 2..5 poster moves`)
  }
  for (const [index, move] of theme.poster_moves.entries()) requireText(theme.id, `poster_moves[${index}]`, move, 180)
  for (const role of ['display_tracking', 'label_tracking', 'body_tracking', 'measure'] as const) {
    requireText(theme.id, `type_treatment.${role}`, theme.type_treatment[role], 80)
  }
  if (!['sentence', 'upper'].includes(theme.type_treatment.label_case)) {
    throw new PptError('PPT_THEME_INVALID', `theme ${theme.id} type_treatment.label_case is invalid`)
  }
  if (!['tabular', 'proportional'].includes(theme.type_treatment.numerals)) {
    throw new PptError('PPT_THEME_INVALID', `theme ${theme.id} type_treatment.numerals is invalid`)
  }
  if (theme.avoid.length === 0 || theme.avoid.length > 6) {
    throw new PptError('PPT_THEME_INVALID', `theme ${theme.id} needs 1..6 avoid rules`)
  }
  for (const [index, rule] of theme.avoid.entries()) requireText(theme.id, `avoid[${index}]`, rule, 160)
  if (theme.gradients.length > 2) {
    throw new PptError('PPT_THEME_INVALID', `theme ${theme.id} may carry at most two gradients`)
  }
  const groups = new Set<string>()
  for (const gradient of theme.gradients) {
    if (!GRADIENT_GROUP.includes(gradient.group)) {
      throw new PptError('PPT_THEME_INVALID', `theme ${theme.id} gradient "${gradient.name}" has an invalid group`)
    }
    if (groups.has(gradient.group)) {
      throw new PptError('PPT_THEME_INVALID', `theme ${theme.id} has more than one ${gradient.group} gradient`)
    }
    groups.add(gradient.group)
    requireText(theme.id, `gradient "${gradient.name}" name`, gradient.name, 80)
    requireText(theme.id, `gradient "${gradient.name}" note`, gradient.note, 240)
    if (gradient.stops.length < 2 || gradient.stops.length > 4) {
      throw new PptError('PPT_THEME_INVALID', `theme ${theme.id} gradient "${gradient.name}" needs 2..4 stops`)
    }
    gradient.stops.forEach((stop, index) => requireColor(theme.id, `gradient "${gradient.name}" stop[${index}]`, stop))
    if (!Number.isInteger(gradient.angle) || gradient.angle < 0 || gradient.angle > 359) {
      throw new PptError('PPT_THEME_INVALID', `theme ${theme.id} gradient "${gradient.name}" angle must be 0..359`)
    }
    if (!Number.isInteger(gradient.max_pages) || gradient.max_pages < 1 || gradient.max_pages > 3) {
      throw new PptError('PPT_THEME_INVALID', `theme ${theme.id} gradient "${gradient.name}" max_pages must be 1..3`)
    }
  }
  if (theme.composition_cycle.length === 0) {
    throw new PptError('PPT_THEME_INVALID', `theme ${theme.id} needs at least one composition`)
  }
  if (theme.background_cycle.length === 0) {
    throw new PptError('PPT_THEME_INVALID', `theme ${theme.id} needs at least one background role`)
  }
  for (const composition of theme.composition_cycle) {
    if (!(ART_COMPOSITIONS as readonly string[]).includes(composition)) {
      throw new PptError('PPT_THEME_INVALID', `theme ${theme.id} has unknown composition: ${composition}`)
    }
  }
  for (const background of theme.background_cycle) {
    if (!(ART_BACKGROUNDS as readonly string[]).includes(background)) {
      throw new PptError('PPT_THEME_INVALID', `theme ${theme.id} has unknown background role: ${background}`)
    }
  }
  return theme
}

